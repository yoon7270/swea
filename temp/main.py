def is_vaildation(user: dict):
    is_vaild = True
    not_vaildate = []
    for black_company in black_list:
        if black_company == user['company']:
            return False, 'blocked'
    if not any(blood_type == user['blood_group'] for blood_type in blood_types):
        is_vaild = False
        not_vaildate.append('blood_group')
    if not any('@' == character for character in user['mail']):
        is_vaild = False
        not_vaildate.append('mail')
    if len(user['name']) < 2 or len(user['name']) > 30:
        is_vaild = False
        not_vaildate.append('name')
    if len(user['website']) < 1:
        is_vaild = False
        not_vaildate.append('website')

    if len(not_vaildate) == 0:
        return is_vaild, 'true'
    elif len(not_vaildate) == 1:
        return is_vaild, not_vaildate[0]
    else:
        return is_vaild, not_vaildate


